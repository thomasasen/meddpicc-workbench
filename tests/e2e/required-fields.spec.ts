test('Metric Builder: erforderliche Messwerte wechseln mit dem Berechnungstyp', async ({ page }) => {
  await page.goto('/meddpicc-workbench/#/tools/metric-builder')
  await expect(page.locator('.metric-fields--discovery textarea').first()).toHaveAttribute('aria-invalid', 'true')
  await page.getByRole('button', { name: /Weiter/ }).click()
  const volume = page.locator('.metric-fields input[placeholder="Anzahl"]')
  await expect(volume).toHaveAttribute('aria-invalid', 'true')
  await volume.fill('50')
  await expect(volume).toHaveAttribute('aria-invalid', 'false')
  await page.locator('.metric-fields select').first().selectOption('qualitative')
  await expect(volume).toHaveCount(0)
  const currentState = page.locator('.metric-fields textarea').first()
  await expect(currentState).toHaveAttribute('aria-invalid', 'true')
  await currentState.fill('Manuelle Nacharbeit')
  await expect(currentState).toHaveAttribute('aria-invalid', 'false')
})

