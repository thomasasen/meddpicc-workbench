import { expect, test } from '@playwright/test'

test('Quick Payback: Fehlende Beträge sind markiert und verschwinden nach Korrektur', async ({ page }) => {
  await page.goto('/meddpicc-workbench/#/tools/quick-payback')
  const investment = page.locator('#quick-upfront')
  const benefit = page.locator('#quick-benefit')
  const runningCosts = page.locator('#quick-operating')

  await expect(investment).toHaveAttribute('aria-invalid', 'true')
  await expect(benefit).toHaveAttribute('aria-invalid', 'true')
  await expect(runningCosts).toHaveAttribute('aria-invalid', 'false')
  await investment.fill('120.000')
  await benefit.fill('240.000')
  await expect(investment).toHaveAttribute('aria-invalid', 'false')
  await expect(benefit).toHaveAttribute('aria-invalid', 'false')
  await expect(page.locator('.quick-duration')).toBeVisible()
  await benefit.fill('falsch')
  await expect(benefit).toHaveAttribute('aria-invalid', 'true')
})

