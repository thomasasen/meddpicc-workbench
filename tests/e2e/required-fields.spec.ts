test('Value Bridge: finanzielle Nachweise erst bei ausdrücklicher Anrechnung', async ({ page }) => {
  await page.goto('/meddpicc-workbench/#/tools/value-bridge')
  await page.getByRole('button', { name: '3 · Metrics & Wert' }).click()
  const metric = page.locator('.vb-metric-entry').first()
  const name = metric.locator('input[placeholder="z. B. Kosten externer Nachbearbeitung"]')
  await expect(name).toHaveAttribute('aria-invalid', 'false')
  await metric.locator('select').first().selectOption('saving')
  await metric.locator('details summary').click()
  await metric.locator('input[type="checkbox"]').check()
  await expect(name).toHaveAttribute('aria-invalid', 'true')
  await name.fill('Nachbearbeitung')
  await expect(name).toHaveAttribute('aria-invalid', 'false')
  await expect(metric.locator('input[placeholder="Noch unbewiesen"]')).toHaveAttribute('aria-invalid', 'true')
})

